#!/usr/bin/env python3
"""Write retoque/hooks/Vulkan_DeviceCreateChainTypes.h from the Vulkan registry the build's headers come from.

The table lists every structure vulkan_core.h defines that the registry allows in a VkDeviceCreateInfo's pNext
chain, with its size, so OptiScaler's vkCreateDevice hook can copy a game's whole chain into storage it owns.
Run it after external/vulkan moves; tests/vk-create-contract fails while the committed header differs.

    python3 tools/gen-vk-device-chain-types.py           # rewrite the header
    python3 tools/gen-vk-device-chain-types.py --check   # exit 1 if it is stale
"""
from pathlib import Path
import re
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
REGISTRY = ROOT / 'external/vulkan/registry/vk.xml'
CORE = ROOT / 'external/vulkan/include/vulkan/vulkan_core.h'
OUT = ROOT / 'retoque/hooks/Vulkan_DeviceCreateChainTypes.h'


def generate():
    core = CORE.read_text()
    defined = set(re.findall(r'^typedef struct (Vk\w+) \{', core, re.M))
    enums = set(re.findall(r'^\s+(VK_STRUCTURE_TYPE_\w+) = ', core, re.M))
    rows = []
    for t in ET.parse(REGISTRY).getroot().iter('type'):
        if t.get('category') != 'struct' or t.get('alias') is not None:
            continue
        if 'VkDeviceCreateInfo' not in (t.get('structextends') or '').split(','):
            continue
        name = t.get('name')
        stype = next((m.get('values') for m in t.findall('member') if m.findtext('name') == 'sType'), None)
        if name in defined and stype in enums:
            rows.append((stype, name))
    rows.sort()
    lines = [
        '// Generated by tools/gen-vk-device-chain-types.py from external/vulkan/registry/vk.xml; do not edit.',
        '// Every structure vulkan_core.h defines that may extend VkDeviceCreateInfo, with its size: what the',
        "// vkCreateDevice hook needs to copy a game's whole pNext chain into storage the call owns.",
        '#pragma once',
        '',
        '#include <vulkan/vulkan_core.h>',
        '',
        '#include <cstddef>',
        '',
        'namespace VulkanDeviceCreateChain',
        '{',
        'struct ChainType',
        '{',
        '    VkStructureType sType;',
        '    size_t size;',
        '};',
        '',
        'inline constexpr ChainType kTypes[] = {',
    ]
    for stype, name in rows:
        row = f'    {{ {stype}, sizeof({name}) }},'
        # clang-format's own break for a row past 120 columns, so the generated file passes the style check
        lines.append(row if len(row) <= 120 else f'    {{ {stype},\n      sizeof({name}) }},')
    lines += ['};', '} // namespace VulkanDeviceCreateChain', '']
    return '\n'.join(lines), len(rows)


if __name__ == '__main__':
    text, count = generate()
    if '--check' in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f'{OUT.relative_to(ROOT)} is stale: run tools/gen-vk-device-chain-types.py')
        print(f'{OUT.relative_to(ROOT)} matches the registry ({count} structures)')
    else:
        OUT.write_text(text)
        print(f'wrote {OUT.relative_to(ROOT)} ({count} structures)')
