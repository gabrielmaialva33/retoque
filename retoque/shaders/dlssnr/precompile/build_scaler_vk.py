#!/usr/bin/env python3
"""Regenerate only the NR Vulkan scaler modules and their embedded header.

Requires native DXC with SPIR-V support and SPIRV-Tools. Does not use a Wine
prefix. All variants compile and validate before any generated artifact changes.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
VARIANTS = ('bcus', 'bcds_bicubic', 'bcds_catmull', 'bcds_lanczos2', 'bcds_lanczos3',
            'bcds_kaiser2', 'bcds_kaiser3', 'bcds_magc', 'fsr_easu')
FLAGS = ('-spirv', '-fspv-target-env=vulkan1.0', '-T', 'cs_6_0', '-E', 'CSMain',
         '-O3', '-Qstrip_debug', '-D', 'VK_MODE')
HEADER = 'DlssNr_Scaler_Shaders_Vk.h'
MANIFEST = 'DlssNr_Scaler_Shaders_Vk.json'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def executable(value):
    found = shutil.which(value)
    if not found:
        raise SystemExit(f'required shader tool not found: {value}')
    return found


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--dxc', default='dxc')
    parser.add_argument('--spirv-val', default='spirv-val')
    args = parser.parse_args(argv)
    compiler, validator = executable(args.dxc), executable(args.spirv_val)
    identity = subprocess.run([compiler, '--version'], check=True, text=True,
                              stdout=subprocess.PIPE, stderr=subprocess.STDOUT).stdout.strip()
    validator_identity = subprocess.run([validator, '--version'], check=True, text=True,
                                        stdout=subprocess.PIPE, stderr=subprocess.STDOUT).stdout.splitlines()[0]
    sources = [HERE/'dlssnr_scaler_vk.hlsl', HERE/'dlssnr_scaler_bcus.hlsl', Path(__file__).resolve()]
    upstream = ROOT/'OptiScaler/shaders/output_scaling'
    sources.extend(upstream/'precompile'/(variant + '.hlsl') for variant in VARIANTS[:-1])
    sources.extend(upstream/'fsr1'/name for name in ('fsr_easu.hlsl', 'ffx_a.h', 'ffx_fsr1.h'))
    source_hashes = {str(path.relative_to(ROOT)): sha(path) for path in sources}
    with tempfile.TemporaryDirectory(prefix='.nr-scaler-', dir=HERE) as temporary:
        stage = Path(temporary)
        for variant in VARIANTS:
            output = stage/(variant + '.spv')
            command = [compiler, *FLAGS, '-D', 'NR_SCALER_' + variant.upper(),
                       '-I', str(ROOT/'OptiScaler'), str(HERE/'dlssnr_scaler_vk.hlsl'), '-Fo', str(output)]
            subprocess.run(command, check=True)
            subprocess.run([validator, '--target-env', 'vulkan1.0', str(output)], check=True)
        lines = ['#pragma once', '', '// Generated by build_scaler_vk.py; do not edit by hand.', '']
        for variant in VARIANTS:
            blob = (stage/(variant + '.spv')).read_bytes()
            lines.append('inline static const unsigned char nr_' + variant + '_spv[] = {')
            for offset in range(0, len(blob), 12):
                lines.append('    ' + ', '.join(f'0x{value:02x}' for value in blob[offset:offset+12]) + ',')
            lines.extend(('};', ''))
        (stage/HEADER).write_text('\n'.join(lines), encoding='utf-8')
        subprocess.run([sys.executable, str(ROOT/'tests/nr-vk-scaler/shader_contract.py'),
                        '--header', str(stage/HEADER), '--spv-dir', str(stage)], check=True)
        if any(sha(ROOT/path) != digest for path, digest in source_hashes.items()):
            raise RuntimeError('shader sources changed during compilation')
        manifest = {'schema': 'retoque-nr-scaler-shaders', 'version': 1,
                    'compiler': {'version': identity, 'executable_sha256': sha(Path(compiler))},
                    'validator': validator_identity, 'flags': list(FLAGS),
                    'sources_sha256': source_hashes, 'header_sha256': sha(stage/HEADER),
                    'spirv_sha256': {variant: sha(stage/(variant + '.spv')) for variant in VARIANTS}}
        (stage/MANIFEST).write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
        destination = HERE/'scaler'
        destination.mkdir(exist_ok=True)
        for variant in VARIANTS:
            os.replace(stage/(variant + '.spv'), destination/(variant + '.spv'))
        os.replace(stage/HEADER, HERE/HEADER)
        os.replace(stage/MANIFEST, HERE/MANIFEST)
    print(f'validated and generated {len(VARIANTS)} NR-only RGBA16F scaler modules')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
